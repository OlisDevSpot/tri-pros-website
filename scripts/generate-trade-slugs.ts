/* eslint-disable perfectionist/sort-imports -- load-env must run before any module that reads process.env */
import './lib/load-env'
import { writeFileSync } from 'node:fs'
import process from 'node:process'
import { catalogSource } from '@/shared/modules/construction/sources'

const OUT = 'src/shared/modules/construction/core/constants/trade-slugs.ts'

// No timestamp in the output, so a re-run with no catalog change leaves the file byte-identical
// and a diff after a re-run always means the catalog moved.
async function main() {
  const trades = await catalogSource.getTrades()
  const slugs = [...new Set(trades.map(trade => trade.slug))].sort()
  const body = [
    '// GENERATED by scripts/generate-trade-slugs.ts — do not edit by hand.',
    'export const tradeSlugs = [',
    ...slugs.map(slug => `  '${slug}',`),
    '] as const',
    '',
    'export type TradeSlug = (typeof tradeSlugs)[number]',
    '',
  ].join('\n')
  writeFileSync(OUT, body)

  console.log(`✓ wrote ${slugs.length} slugs to ${OUT}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
